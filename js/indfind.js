  function match(q, D) {
    q = norm(q);
    if (q.length < 1) return [];
    var out = [];
    (D && D.INDUSTRIES || []).forEach(function (ind) {
      if (D.isOpen && !D.isOpen(ind.id)) return;
      var words = (NK[ind.id] || []).concat(norm(ind.label).length ? ind.label.split(/[·・\s]/).map(norm) : []);
      var best = 0;
      words.forEach(function (w) {
        if (!w) return;
        var s = 0;
        if (q === w) s = 20 + w.length;                       // 똑같음
        else if (q.indexOf(w) >= 0) s = 10 + w.length;        // '여수네일숍'에 '네일' 들어 있음
        else if (q.length >= 2 && w.indexOf(q) === 0) s = 6 + q.length; // '네' → 앞부분 맞음
        else if (q.length >= 2 && w.indexOf(q) > 0) s = 3 + q.length;
        if (s > best) best = s;
      });
      if (best) out.push({ id: ind.id, score: best });
    });
    out.sort(function (a, b) { return b.score - a.score; });
    return out;
  }
