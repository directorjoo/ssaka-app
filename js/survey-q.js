  // 받침 따라 을/를, 이/가, 는/은 맞추기
  function josa(s) {
    return s.replace(/([가-힣])\{(을를|이가|은는)\}/g, function (m, ch, p) {
      var has = (ch.charCodeAt(0) - 0xAC00) % 28 > 0;
      var pair = { '을를': ['을', '를'], '이가': ['이', '가'], '은는': ['은', '는'] }[p];
      return ch + (has ? pair[0] : pair[1]);
    });
  }
  function fill(s, ind) {
    return josa(s.replace(/\{곳\}를/g, '{곳}{을를}').replace(/\{곳\}는/g, '{곳}{은는}').replace(/\{손님\}이/g, '{손님}{이가}')
      .replace(/\{곳\}/g, ind.w).replace(/\{손님\}/g, ind.c));
  }
  function parse(line, id, ind) {
    var key = line.charAt(0) === '!'; if (key) line = line.slice(1);
    var p = line.split('|');
    return { id: id, q: fill(p[0], ind), ex: fill(p[1] || '', ind), t: (p[2] || '0').split(',').map(Number), key: key };
  }
